import { test, expect, signup, activityType, publish, png } from './helpers'

test('create, publish, reload, edit and delete a presentation through the UI', async ({ page }) => {
    await signup(page)
    await page.goto('/create')
    await page.getByLabel('Quiz title').fill('A browser-created presentation')
    await activityType(page, 'TEXT_SLIDE')
    await page.getByLabel('Question text', { exact: true }).fill('Welcome from the UI')
    await page.getByLabel('Slide body', { exact: true }).fill('Saved in the real local Firestore emulator.')
    await publish(page)
    const list = await (await page.request.get('/api/quiz')).json()
    expect(list).toHaveLength(1)
    const deck = list[0]
    expect(deck.questions[0]).toMatchObject({ type: 'TEXT_SLIDE', text: 'Welcome from the UI' })
    await page.goto(`/edit/${deck.id}`)
    await expect(page.getByLabel('Slide body')).toHaveValue('Saved in the real local Firestore emulator.')
    await page.getByLabel('Quiz title').fill('Edited presentation')
    await publish(page)
    const edited = await (await page.request.get(`/api/quiz?id=${deck.id}`)).json()
    expect(edited.title).toBe('Edited presentation')
    expect(edited.questions[0].id).toBe(deck.questions[0].id)
    expect(edited.versionId).not.toBe(deck.publishedVersionId)
    page.once('dialog', dialog => dialog.accept())
    await page.getByRole('button', { name: 'Delete event', exact: true }).click()
    await expect.poll(async () => (await (await page.request.get('/api/quiz')).json()).length).toBe(0)
})

test('media upload previews and retrieves bytes through the signed media API', async ({ page }) => {
    await signup(page)
    await page.goto('/create')
    await page.getByLabel('Quiz title').fill('Media presentation')
    await activityType(page, 'TEXT_SLIDE')
    await page.getByLabel('Question text', { exact: true }).fill('Uploaded image')
    await page.getByLabel('Upload question media').setInputFiles({ name: 'tiny.png', mimeType: 'image/png', buffer: png })
    await expect(page.getByLabel('Remove media')).toBeVisible()
    const image = page.locator('img').filter({ visible: true }).first()
    await expect.poll(() => image.evaluate((e: HTMLImageElement) => e.complete && e.naturalWidth > 0)).toBe(true)
    const src = await image.getAttribute('src')
    expect(src).toMatch(/^\/api\/media\/media\//)
    const response = await page.request.get(src!)
    expect(response.status()).toBe(200)
    expect(response.headers()['content-type']).toContain('image/png')
    expect(await response.body()).toEqual(png)
    await publish(page)
    const [deck] = await (await page.request.get('/api/quiz')).json()
    expect(deck.questions[0].mediaUrl).toBe(src)
    await page.goto(`/edit/${deck.id}`)
    await page.getByLabel('Remove media').click()
    await expect(page.getByLabel('Upload question media')).toBeAttached()
    await publish(page)
    const saved = await (await page.request.get(`/api/quiz?id=${deck.id}`)).json()
    expect(saved.questions[0].mediaUrl || '').toBe('')
})

test('editor rejects incomplete answers and unsupported uploads', async ({ page }) => {
    await signup(page)
    await page.goto('/create')
    await page.getByRole('button', { name: 'Save and publish presentation', exact: true }).filter({ visible: true }).first().click()
    await expect(page.locator('p[role=alert]')).toHaveText('Please enter a quiz title')
    await page.getByLabel('Quiz title').fill('Validation checks')
    await page.getByLabel('Question text', { exact: true }).fill('Incomplete question')
    await page.getByRole('button', { name: 'Save and publish presentation', exact: true }).filter({ visible: true }).first().click()
    await expect(page.locator('p[role=alert]')).toContainText('required answers')
    await page.getByLabel('Upload question media').setInputFiles({ name: 'unsafe.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg xmlns="http://www.w3.org/2000/svg"></svg>') })
    await expect(page.locator('p[role=alert]')).toContainText('Choose a JPEG')
    expect(await (await page.request.get('/api/quiz')).json()).toEqual([])
})

test('true/false, typed answers and slides keep their content and order after publication', async ({ page }) => {
    await signup(page)
    await page.goto('/create')
    await page.getByLabel('Quiz title').fill('Mixed activity types')
    await activityType(page, 'TRUE_FALSE')
    await page.getByLabel('Question text', { exact: true }).fill('The sky is blue')
    await page.getByLabel('Mark answer 1 correct', { exact: true }).click()
    const mobile = (page.viewportSize()?.width || 1280) < 1024
    const add = () => (mobile ? page.getByRole('navigation') : page.getByRole('complementary')).getByRole('button', { name: 'Add', exact: true }).click()
    await add()
    await activityType(page, 'TYPE_ANSWER')
    await page.getByLabel('Question text', { exact: true }).fill('Name our planet')
    await page.getByLabel('Correct typed answer', { exact: true }).fill('Earth')
    await add()
    await activityType(page, 'TEXT_SLIDE')
    await page.getByLabel('Question text', { exact: true }).fill('Read before answering')
    await page.getByLabel('Slide body', { exact: true }).fill('This slide moves before the typed answer.')
    if (mobile) await page.getByRole('button', { name: 'Settings', exact: true }).click()
    await page.getByRole('button', { name: 'Move up', exact: true }).click()
    if (mobile) await page.getByRole('button', { name: 'Close settings', exact: true }).click()
    await publish(page)
    const [deck] = await (await page.request.get('/api/quiz')).json()
    expect(deck.questions.map((q: { type: string }) => q.type)).toEqual(['TRUE_FALSE', 'TEXT_SLIDE', 'TYPE_ANSWER'])
    expect(JSON.parse(deck.questions[0].options)).toEqual(['True', 'False'])
    expect(deck.questions[0].correct).toBe(0)
    expect(JSON.parse(deck.questions[2].options)).toEqual(['Earth'])
    expect(deck.questions[1].body).toBe('This slide moves before the typed answer.')
    const ids = deck.questions.map((q: { id: string }) => q.id)
    expect(new Set(ids).size).toBe(3)
    await page.goto(`/edit/${deck.id}`)
    await expect(page.getByLabel('Question text', { exact: true })).toHaveValue('The sky is blue')
    await publish(page)
    const saved = await (await page.request.get(`/api/quiz?id=${deck.id}`)).json()
    expect(saved.questions.map((q: { id: string }) => q.id)).toEqual(ids)
})
